// Subsets Fusion Pixel Font (OFL) BDF bitmaps down to just the characters
// used anywhere in src/, and writes src/font-data.js.
//   node tools/build-font.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = {
  f12: 'assets/fonts/fusion-pixel-12px-proportional-zh_hans.bdf',
  f10: 'assets/fonts/fusion-pixel-10px-proportional-zh_hans.bdf',
  f8: 'assets/fonts/fusion-pixel-8px-proportional-zh_hans.bdf',
};

// 1. collect characters (skip files whose text is HTML or comments, never drawn in pixels)
const SKIP = ['font-data.js', 'script-data.js', 'audio.js', 'player.js'];
const chars = new Set();
for (let c = 32; c < 127; c++) chars.add(String.fromCharCode(c));
function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (p.endsWith('.js') && !SKIP.some(s => p.endsWith(s))) for (const ch of fs.readFileSync(p, 'utf8')) if (ch.codePointAt(0) > 127) chars.add(ch);
  }
}
walk(path.join(root, 'src'));
// box-drawing / symbols the terminal scene composes at runtime
for (const ch of '✓✗✻●○◆◇▸▹›»…—·•→←↑↓★☆♪♫❤█▌▐▀▄─│╭╮╰╯┌┐└┘├┤') chars.add(ch);

// 2. parse BDF, keep needed glyphs
function parseBDF(file) {
  const lines = fs.readFileSync(path.join(root, file), 'utf8').split('\n');
  const glyphs = {};
  let cur = null, inBitmap = false;
  for (const ln of lines) {
    if (ln.startsWith('STARTCHAR')) { cur = { rows: [] }; inBitmap = false; continue; }
    if (!cur) continue;
    if (ln.startsWith('ENCODING')) cur.cp = parseInt(ln.split(/\s+/)[1], 10);
    else if (ln.startsWith('DWIDTH')) cur.adv = parseInt(ln.split(/\s+/)[1], 10);
    else if (ln.startsWith('BBX')) { const [, w, h, xo, yo] = ln.trim().split(/\s+/).map(Number); Object.assign(cur, { w, h, xo, yo }); }
    else if (ln.startsWith('BITMAP')) inBitmap = true;
    else if (ln.startsWith('ENDCHAR')) {
      if (cur.cp >= 0) {
        const ch = String.fromCodePoint(cur.cp);
        if (chars.has(ch) && !glyphs[ch]) glyphs[ch] = [cur.adv, cur.w, cur.h, cur.xo, cur.yo, cur.rows.join('')];
      }
      cur = null; inBitmap = false;
    } else if (inBitmap) cur.rows.push(ln.trim());
  }
  return glyphs;
}

const out = {};
const missing = {};
for (const [id, file] of Object.entries(FONTS)) {
  const glyphs = parseBDF(file);
  let asc = 0, desc = 0;
  for (const g of Object.values(glyphs)) { asc = Math.max(asc, g[4] + g[2]); desc = Math.max(desc, -g[4]); }
  out[id] = { ascent: asc, descent: desc, glyphs };
  missing[id] = [...chars].filter(c => !glyphs[c]);
}

const js = `// AUTO-GENERATED by tools/build-font.js — do not edit.
// Glyph subset of Fusion Pixel Font by TakWolf, SIL Open Font License 1.1.
// glyph: [advance, w, h, xoff, yoff, hexRows]
export const FONT_DATA = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(root, 'src/font-data.js'), js);
console.log(`chars: ${chars.size}; size: ${(js.length / 1024).toFixed(1)} KB`);
for (const [id, m] of Object.entries(missing)) if (m.length) console.log(`${id} missing: ${m.join('')}`);
